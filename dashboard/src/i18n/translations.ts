const listeners = new Set<(lang: Language) => void>();

function getInitialLanguage(): Language {
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('godhand_lang');
    if (saved === 'en' || saved === 'de') return saved;
  }
  return 'de';
}

let currentLanguage: Language = getInitialLanguage();

function setLanguage(lang: Language) {
  currentLanguage = lang;
  if (typeof window !== 'undefined') {
    localStorage.setItem('godhand_lang', lang);
    window.dispatchEvent(new CustomEvent('godhand-lang-change', { detail: lang }));
  }
  listeners.forEach(fn => {
    try {
      fn(lang);
    } catch (e) {
      console.error("Language listener error:", e);
    }
  });
}

function getLanguage(): Language {
  return currentLanguage;
}

function t(key: keyof typeof translations['en'], params?: Record<string, string>): string {
  const dict = translations[currentLanguage] || translations['en'];
  const hasKey = dict && typeof (dict as any)[key] === 'string';
  let text = (dict as any)[key] || (translations['en'] as any)[key];
  if (!text) {
    if (typeof console !== 'undefined' && console.warn) {
      console.warn(`[GodHand i18n Guard] ⚠️ Missing or hardcoded translation key requested: "${String(key)}" (Language: ${currentLanguage})`);
    }
    text = String(key);
  }
  if (params) {
    Object.keys(params).forEach(paramKey => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), params[paramKey]);
    });
  }
  return text;
}

export function useTranslation() {
  const [lang, setLang] = React.useState<Language>(currentLanguage);

  React.useEffect(() => {
    const handler = (newLang: Language) => setLang(newLang);
    listeners.add(handler);
    return () => {
      listeners.delete(handler);
    };
  }, []);

  const translate = React.useCallback(
    (key: keyof typeof translations['en'], params?: Record<string, string>) => t(key, params),
    [lang]
  );

  return {
    t: translate,
    language: lang,
    setLanguage
  };
}
